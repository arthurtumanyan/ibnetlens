#include <inttypes.h>

#include "ibnetlens.h"

static char kind_letter(const ib_node *n)
{
    return n->kind == IB_SWITCH ? 'S' : n->kind == IB_ROUTER ? 'R' : 'H';
}

/* Layout of the former topo_parser report, kept byte-compatible. */
void ib_write_legacy(const ib_fabric *f, FILE *out)
{
    for (size_t i = 0; i < f->nnodes; i++) {
        const ib_node *n = &f->nodes[i];
        bool sw = n->kind == IB_SWITCH;

        fprintf(out, "%s:\n", sw ? "Switch" : "Host");
        fprintf(out, "sysimgguid: 0x%" PRIx64 "\n", n->sysimg);
        fprintf(out, "%s: 0x%" PRIx64, sw ? "switch_id: " : "port_id: ", n->guid);
        if (sw)
            fprintf(out, "(%" PRIx64 ")", n->portguid);
        fputc('\n', out);

        for (uint32_t k = 0; k < n->nports; k++) {
            const ib_port *p = &f->ports[n->first_port + k];
            fprintf(out, "\tConnected to %s: %s=0x%" PRIx64,
                    p->peer_kind == 'S' ? "switch" : "host",
                    p->peer_kind == 'S' ? "switchguid" : "caguid", p->peer_guid);
            if (p->peer_node != IBT_NONE && f->nodes[p->peer_node].kind == IB_SWITCH)
                fprintf(out, "(%" PRIx64 ")", f->nodes[p->peer_node].portguid);
            fprintf(out, ", port=%u\n", p->peer_num);
        }
        fputc('\n', out);
    }
}

static void put_speed(FILE *out, const ib_port *p)
{
    if (p->speed != IB_SPEED_UNKNOWN)
        fprintf(out, " %ux%s", p->width, ib_speed_name((ib_speed)p->speed));
}

static const char *peer_desc(const ib_fabric *f, const ib_port *p)
{
    return p->peer_node == IBT_NONE ? "" : ib_str(f, f->nodes[p->peer_node].desc);
}

static void write_node_header(const ib_fabric *f, const ib_node *n, FILE *out)
{
    fprintf(out, "vendid=0x%x\ndevid=0x%x\nsysimgguid=0x%" PRIx64 "\n", n->vendid, n->devid, n->sysimg);
    if (n->kind == IB_SWITCH)
        fprintf(out, "switchguid=0x%" PRIx64 "(%" PRIx64 ")\n", n->guid, n->portguid);
    else
        fprintf(out, "caguid=0x%" PRIx64 "\n", n->guid);

    const char *label = n->kind == IB_SWITCH ? "Switch" : n->kind == IB_ROUTER ? "Rt" : "Ca";
    fprintf(out, "%s\t%u \"%c-%016" PRIx64 "\"\t\t# \"%s\"", label, n->declared_ports, kind_letter(n),
            n->guid, ib_str(f, n->desc));
    if (n->base_type != IB_BASE_NONE)
        fprintf(out, " %s port %u lid %u lmc %u", n->base_type == IB_BASE_ENHANCED ? "enhanced" : "base",
                n->base_port, n->lid, n->lmc);
    fputc('\n', out);
}

/* Emits a file that ibnetdiscover consumers (and ibnetlens itself) read back unchanged. */
void ib_write_ibnd(const ib_fabric *f, FILE *out)
{
    fprintf(out, "#\n# Topology file: generated by ibnetlens " IBNETLENS_VERSION "\n#\n\n");
    for (size_t i = 0; i < f->nnodes; i++) {
        const ib_node *n = &f->nodes[i];
        write_node_header(f, n, out);
        for (uint32_t k = 0; k < n->nports; k++) {
            const ib_port *p = &f->ports[n->first_port + k];
            if (n->kind != IB_SWITCH) {
                fprintf(out, "[%u](%" PRIx64 ") \t\"%c-%016" PRIx64 "\"[%u]\t\t# lid %u lmc %u \"%s\" lid %u",
                        p->num, p->portguid, p->peer_kind, p->peer_guid, p->peer_num, p->lid, p->lmc,
                        peer_desc(f, p), p->peer_lid);
            } else {
                fprintf(out, "[%u]\t\"%c-%016" PRIx64 "\"[%u]", p->num, p->peer_kind, p->peer_guid, p->peer_num);
                if (p->peer_portguid)
                    fprintf(out, "(%" PRIx64 ") ", p->peer_portguid);
                fprintf(out, "\t\t# \"%s\" lid %u", peer_desc(f, p), p->peer_lid);
            }
            put_speed(out, p);
            fputc('\n', out);
        }
        fputc('\n', out);
    }
}
